type ImageUploadFieldProps = {
  label: string;
  value: string;
  onUrlChange: (url: string) => void;
  helper?: string;
};

function ImageUploadField({ label, value, onUrlChange, helper }: ImageUploadFieldProps) {
  const [uploading, setUploading] = useState(false);
  const [fileName, setFileName] = useState('');
  const [error, setError] = useState<string | null>(null);

  const handleFile = async (event: ChangeEvent<HTMLInputElement>) => {
    const file = event.target.files?.[0];
    if (!file) return;
    setUploading(true);
    setError(null);
    setFileName(file.name);
    try {
      const response = await uploadImage(file);
      onUrlChange(response.url);
    } catch (uploadError) {
      setError(uploadError instanceof Error ? uploadError.message : 'Upload failed');
    } finally {
      setUploading(false);
    }
  };

  return (
    <label className="auth-label wide-field">
      {label}
      <input className="auth-input auth-file" type="file" accept="image/*" onChange={handleFile} />
      <input className="auth-input" value={value} readOnly placeholder="Upload an image to populate the URL" />
      {value ? <img className="admin-preview" src={value} alt={label} /> : null}
      <small className="auth-help">{uploading ? 'Uploading to MinIO…' : error ?? helper ?? fileName}</small>
    </label>
  );
}

function AutoCatalogIdPreview({ title }: { title: string }) {
  const generated = useMemo(() => {
    const slug = title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '');
    return `${slug || 'catalog'}-auto`;
  }, [title]);

  return (
    <label className="auth-label">
      Catalog ID
      <input className="auth-input" value={generated} readOnly placeholder="Auto-generated by backend" />
      <small className="auth-help">Created automatically when the form is saved.</small>
    </label>
  );
}

function buildMatchId(homeTeam: string, awayTeam: string, date: string) {
  const slug = `${homeTeam}-${awayTeam}-${date}`.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  return `${slug || 'match'}-auto`;
}

